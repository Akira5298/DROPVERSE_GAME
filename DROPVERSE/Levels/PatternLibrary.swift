import Foundation

/// Movement mode of the player.
enum MovementMode: String, Codable, Hashable, Sendable {
    case cube, ship, wave
}

/// Player state a pattern requires on entry / guarantees on exit.
struct PatternState: Codable, Hashable, Sendable {
    var mode: MovementMode
    var gravity: String?
    var mini: Bool?

    var isFlipped: Bool { gravity == "flipped" }
    var isMini: Bool { mini ?? false }

    static let base = PatternState(mode: .cube, gravity: nil, mini: nil)

    /// Compatibility key (mode, gravity, size).
    var key: String { "\(mode.rawValue)|\(isFlipped)|\(isMini)" }
}

struct MotionSpec: Codable, Hashable, Sendable {
    enum Axis: String, Codable, Sendable { case x, y }
    var axis: Axis
    var amp: Double
    var period: Double
    var phase: Double?
}

struct SpeedChange: Codable, Hashable, Sendable {
    var at: Double
    var mult: Double
}

/// One authored object inside a pattern (see Resources/Patterns/patterns.json for units).
struct PatternObject: Codable, Hashable, Sendable {
    var type: String
    var x: Double
    var w: Double?
    var y: Double?
    var h: Double?
    var count: Int?
    var dir: String?
    var style: String?
    var kind: String?
    var r: Double?
    var len: Double?
    var amp: Double?
    var period: Double?
    var phase: Double?
    var on: Double?
    var dur: Double?
    var hmin: Double?
    var hmax: Double?
    var bars: Int?
    var barW: Double?
    var gap: Double?
    var step: Double?
    var orientation: String?
    var move: MotionSpec?
    /// Falling platforms: beat (from pattern start) at which the platform drops.
    var fallAt: Double?
}

/// A validated tap-timing cue for the Rhythm Timing Guide (generated by Tools/annotate_patterns.py).
struct PatternCue: Codable, Hashable, Sendable {
    enum Action: String, Codable, Sendable { case jump, double, orb, gravity }
    /// Beat from the pattern start at which to press.
    var beat: Double
    /// How long the validated strategy holds the press (beats).
    var hold: Double
    /// Symmetric tolerance (beats): pressing anywhere in beat ± window still completes the pattern.
    var window: Double
    var action: Action
}

/// A handcrafted, validated obstacle pattern.
struct PatternTemplate: Codable, Hashable, Identifiable, Sendable {
    var id: String
    var name: String
    /// 1 Challenging, 2 Hard, 3 Very Hard, 4 Expert.
    var difficulty: Int
    /// Musical length in beats.
    var beats: Int
    var entry: PatternState
    var exit: PatternState
    /// Minimum reaction time (reference seconds) the pattern was designed around.
    var minReaction: Double
    var tags: [String]
    var speed: [SpeedChange]?
    var objects: [PatternObject]
    /// 0 = no jump needed, 1 = single jumps suffice, 2 = proven to need the air jump.
    var requiredJumps: Int?
    /// Beats the following pattern must wait so the player has landed with both jumps.
    var settleBeats: Int?
    /// Must start on a bar downbeat (its cues are written against kick/snare positions).
    var barAligned: Bool?
    var cues: [PatternCue]?
    /// Human-readable completion strategies (shown in debug tools).
    var strategies: [String]?

    var isTransition: Bool { tags.contains("transition") }
    var jumpsRequired: Int { requiredJumps ?? 1 }
}

struct PatternLibrary: Codable, Sendable {
    var version: Int
    var patterns: [PatternTemplate]

    func pattern(id: String) -> PatternTemplate? {
        patterns.first { $0.id == id }
    }

    enum LoadError: Error, CustomStringConvertible {
        case missingResource
        case invalid(String)

        var description: String {
            switch self {
            case .missingResource: return "patterns.json is missing from the app bundle (Resources/Patterns)."
            case .invalid(let reason): return "patterns.json is invalid: \(reason)"
            }
        }
    }

    static func decode(_ data: Data) throws -> PatternLibrary {
        let library = try JSONDecoder().decode(PatternLibrary.self, from: data)
        try library.validateStructure()
        return library
    }

    /// Loads the bundled library. Patterns live in a folder reference, so the
    /// subdirectory is tried first, then the bundle root as a fallback.
    static func loadBundled(bundle: Bundle = .main) throws -> PatternLibrary {
        let url = bundle.url(forResource: "patterns", withExtension: "json", subdirectory: "Patterns")
            ?? bundle.url(forResource: "patterns", withExtension: "json")
        guard let url else { throw LoadError.missingResource }
        return try decode(try Data(contentsOf: url))
    }

    /// Structural checks that do not need simulation (the solver lives in LevelValidator).
    func validateStructure() throws {
        var seen = Set<String>()
        let knownTypes: Set<String> = ["spike", "block", "mblock", "pit", "hazard", "mhazard", "notehazard", "saw",
                                       "pendulum", "laser", "gate", "basswall", "eq", "pad", "orb", "portal", "fallblock"]
        for p in patterns {
            guard seen.insert(p.id).inserted else { throw LoadError.invalid("duplicate id \(p.id)") }
            guard p.beats > 0, (1...4).contains(p.difficulty) else { throw LoadError.invalid("bad header in \(p.id)") }
            for o in p.objects {
                guard knownTypes.contains(o.type) else { throw LoadError.invalid("unknown type \(o.type) in \(p.id)") }
                guard o.x >= 0, o.x <= Double(p.beats) else { throw LoadError.invalid("object outside pattern in \(p.id)") }
            }
        }
        for required in ["trans.ship_to_cube", "trans.wave_to_cube", "trans.cube_to_ship"] where pattern(id: required) == nil {
            throw LoadError.invalid("required pattern \(required) missing")
        }
    }
}
